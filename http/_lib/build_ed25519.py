#!/usr/bin/env python3
"""Build http/_lib/ed25519.js — a single ESM module the IntelliJ/ijhttp client can `import`.

The vendored tweetnacl + tweetnacl-util are UMD (no ESM named exports), so each is wrapped in an IIFE
with a local `module` object (steering the UMD into its CommonJS branch) and the result captured. The
module then exports the few helpers an .http pre-request handler needs to drive challenge-response login:
a fixed test Ed25519 keypair derived from a seed, signing the decoded nonce, and the raw public key.

Run: python3 http/_lib/build_ed25519.py   (re-run after bumping a vendored lib)
"""
from pathlib import Path

LIB = Path(__file__).parent
nacl = (LIB / "nacl-fast.min.js").read_text()
util = (LIB / "nacl-util.min.js").read_text()

header = """// GENERATED by build_ed25519.py — do not edit by hand. Vendored: tweetnacl@1.0.3 + tweetnacl-util@0.15.1.
// An ESM facade over the UMD libs so the HTTP client can `import { signNonceB64, publicKeyB64 } from './_lib/ed25519.js'`.
// Used by the *-authed.http suites to produce a real Ed25519 signature over a server login nonce (cr-0013).
"""

# Each UMD checks `typeof module !== 'undefined' && module.exports`; giving it a local `module` via the
# wrapper param makes it take that branch and assign to our captured object, never touching global `this`.
wrap = (
    "const nacl = (function () { const module = { exports: {} };\n"
    + nacl
    + "\nreturn module.exports; })();\n\n"
    + "const naclUtil = (function () { const module = { exports: {} };\n"
    + util
    + "\nreturn module.exports; })();\n\n"
)

footer = """
/** Raw 32-byte Ed25519 public key (base64) for a seed — what setup stores as authPublicKey. */
export function publicKeyB64(seedB64) {
  const kp = nacl.sign.keyPair.fromSeed(naclUtil.decodeBase64(seedB64));
  return naclUtil.encodeBase64(kp.publicKey);
}

/** Base64 Ed25519 signature over the raw bytes of a base64 nonce — what /login/verify expects. */
export function signNonceB64(seedB64, nonceB64) {
  const kp = nacl.sign.keyPair.fromSeed(naclUtil.decodeBase64(seedB64));
  const sig = nacl.sign.detached(naclUtil.decodeBase64(nonceB64), kp.secretKey);
  return naclUtil.encodeBase64(sig);
}

/** Self-check used by the spike: sign a message and verify it round-trips (no backend needed). */
export function selfCheck(seedB64) {
  const kp = nacl.sign.keyPair.fromSeed(naclUtil.decodeBase64(seedB64));
  const msg = naclUtil.decodeUTF8("veyq-spike");
  const sig = nacl.sign.detached(msg, kp.secretKey);
  return nacl.sign.detached.verify(msg, sig, kp.publicKey);
}
"""

(LIB / "ed25519.js").write_text(header + wrap + footer)
print(f"wrote ed25519.js ({len((LIB / 'ed25519.js').read_text())} bytes)")
